#!/usr/bin/env python3
# Generates src/vga/font_pkg.vhd, the font of the text (see src/vga/text.vhd),
# from the Spleen 16x32 font: the printable ASCII characters (codes 32 to
# 126). Spleen is licensed under the BSD 2-Clause license, see
# LICENSE.spleen.
#
# The font file (spleen-16x32.bdf) is not in this repository. The current
# src/vga/font_pkg.vhd is from version 2.2.0, the tag 2.2.0 of the Spleen
# repository. Usage (from the top directory of the repository):
#   git clone --branch 2.2.0 https://github.com/fcambus/spleen
#   python3 font/gen_font_pkg.py spleen/spleen-16x32.bdf > src/vga/font_pkg.vhd
# The version is in the header of the generated file. This script is adapted
# from the one of MandelbrotMEGA65, which only has the digits and a few
# characters.

import sys

WIDTH  = 16
HEIGHT = 32
FIRST  = 32
LAST   = 126


def load_bdf(filename):
    """Returns the version, and a dictionary from code point to the rows of
    the glyph."""
    glyphs  = {}
    version = None
    code    = None
    rows    = None
    for line in open(filename):
        words = line.split()
        if not words:
            continue
        if words[0] == 'FONT_VERSION':
            version = words[1].strip('"')
        elif words[0] == 'FONTBOUNDINGBOX':
            assert words[1:3] == [str(WIDTH), str(HEIGHT)], 'Wrong font size'
        elif words[0] == 'ENCODING':
            code = int(words[1])
        elif words[0] == 'BBX':
            # All glyphs of Spleen fill the whole cell
            assert words[1:3] == [str(WIDTH), str(HEIGHT)], 'Wrong glyph size'
        elif words[0] == 'BITMAP':
            rows = []
        elif words[0] == 'ENDCHAR':
            glyphs[code] = rows
            rows = None
        elif rows is not None:
            rows.append(int(words[0], 16))
    return version, glyphs


def main():
    version, glyphs = load_bdf(sys.argv[1])

    print('-- This file is generated by font/gen_font_pkg.py. Do not edit.')
    print('--')
    print('-- The printable ASCII characters (codes %d to %d) of the Spleen 16x32 font,' % (FIRST, LAST))
    print('-- version %s, from https://github.com/fcambus/spleen (spleen-16x32.bdf):' % version)
    print('--')
    for line in open(sys.argv[0].replace('gen_font_pkg.py', 'LICENSE.spleen')):
        print(('-- ' + line.rstrip()).rstrip())
    print('--')
    print('-- C_FONT holds %d rows of %d pixels for each character, the top row first.' % (HEIGHT, WIDTH))
    print('-- The row r of the character with the code c is at index 32*c + r. The')
    print('-- leftmost pixel is bit 15. The other codes (0 to 31 and 127) are empty.')
    print('')
    print('library ieee;')
    print('use ieee.std_logic_1164.all;')
    print('')
    print('package font_pkg is')
    print('')
    print('   type font_t is array (0 to 4095) of std_logic_vector(%d downto 0);' % (WIDTH-1))
    print('')
    print('   constant C_FONT : font_t := (')
    for c in range(FIRST, LAST + 1):
        rows = glyphs[c]
        print('      -- %r' % chr(c))
        for r, value in enumerate(rows):
            picture = ''.join('#' if value >> (WIDTH-1-i) & 1 else '.' for i in range(WIDTH))
            print('      %4d => "%s",  -- %s' % (HEIGHT*c + r, format(value, '0%db' % WIDTH), picture))
    print('      others => (others => \'0\'));')
    print('')
    print('end package font_pkg;')


if __name__ == '__main__':
    main()
