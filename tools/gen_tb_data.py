#!/usr/bin/env python3
"""Generates the data of the testbenches from the model (tools/model.cpp):

* build/model/model_pkg.vhd: the counts of each puzzle that is simulated
  (SIMULATED below), with the contexts of the puzzle as in the design: the
  nodes (including the root), the solutions, and the passes of the slowest
  context, and the passes until the first solution of each context.
* build/model/<name>_<ctx>.trace for the puzzles in TRACED: every pass of
  every context, one per line: the level of the visited node, the anchor and
  the slot of its last piece, and whether it is counted, skipped, and a
  solution (see "trace" in model.cpp).

Usage: python3 tools/gen_tb_data.py   (or "make tbdata", which "make sim" runs)
"""

import os

import model
import puzzles

# The puzzles that are simulated, and those of them whose traces are checked
SIMULATED = ['5x5', '1x16', '1x27', '7x7', '5x8']
TRACED = ['5x5', '1x16', '1x27', '7x7']


def main():
    ps = {p.name: p for p in model.build()}
    out = []
    w = out.append
    w('-- This file is generated by tools/gen_tb_data.py from the model')
    w('-- (tools/model.cpp). Do not edit.')
    w('--')
    w('-- The results of the model for the puzzles that are simulated, with the')
    w('-- contexts as in the design (see puzzle_pkg.vhd): the nodes (including the')
    w('-- root), the solutions, the passes of the slowest context, and for each')
    w('-- context the number of passes until (and including) its first solution')
    w('-- (0 if it has none). Puzzles that are not simulated have all zeros.')
    w('')
    w('use work.puzzle_pkg.all;')
    w('')
    w('package model_pkg is')
    w('')
    w('   type first_vector is array (natural range <>) of natural;')
    w('')
    w('   type model_t is record')
    w('      nodes      : natural;')
    w('      solutions  : natural;')
    w('      max_passes : natural;')
    w('      first_sol  : first_vector(0 to C_STAGES * C_MAX_ENGINES - 1);')
    w('   end record model_t;')
    w('')
    w('   type model_vector is array (natural range <>) of model_t;')
    w('')
    w('   constant C_MODEL : model_vector(0 to C_NUM_PUZZLES-1) := (')
    order = sorted(ps.values(), key=lambda p: p.index)
    for n, p in enumerate(order):
        end = ',' if n < len(order) - 1 else ');'
        nctx = puzzles.STAGES * p.engines
        if p.name in SIMULATED:
            _, total = model.run(p, p.engines, p.depth)
            firsts = [int(x) for x in model.model(p, 'firsts', p.engines, p.depth)]
            firsts += [0] * (puzzles.STAGES * max(q.engines for q in order) - nctx)
            w(f"      {p.index} => (nodes => {total['nodes']}, solutions => {total['solutions']}, "
              f"max_passes => {total['max_passes']},  -- {p.name}")
            w(f"            first_sol => ({', '.join(map(str, firsts))})){end}")
        else:
            w(f'      {p.index} => (nodes => 0, solutions => 0, max_passes => 0, '
              f'first_sol => (others => 0)){end}  -- {p.name}')
        if p.name in TRACED:
            model.model(p, 'trace', p.engines, p.depth, os.path.join(model.BUILD, p.name))
    w('')
    w('end package model_pkg;')
    with open(os.path.join(model.BUILD, 'model_pkg.vhd'), 'w') as f:
        f.write('\n'.join(out) + '\n')


if __name__ == '__main__':
    main()
