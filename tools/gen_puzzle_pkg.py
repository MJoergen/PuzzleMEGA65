#!/usr/bin/env python3
"""Generates src/main/puzzle_pkg.vhd, the puzzles of the design, from the
puzzle files (puzzles/*.txt) and the list in tools/puzzles.py.

Usage (from the top directory of the repository):
   python3 tools/gen_puzzle_pkg.py > src/main/puzzle_pkg.vhd
or "make puzzles". The number of nodes at the depth of the split of each
puzzle (the frontier, used for the progress) comes from the model
(tools/model.cpp), which is compiled to build/model/ first.
"""

import puzzles
import model


def vhdl_string(s, n):
    assert len(s) <= n, s
    return '"' + s.ljust(n) + '"'


def main():
    ps = model.build()
    max_size = max(len(s['offsets']) for p in ps for s in p.slots)
    max_slots = max(len(p.slots) for p in ps)
    max_width = max(p.width for p in ps)
    max_pieces = max(len(p.pieces) for p in ps)
    max_squares = max(p.squares for p in ps)
    max_rows = max(p.rows for p in ps)
    max_cols = max(p.cols for p in ps)
    max_engines = max(p.engines for p in ps)
    max_cell = max(p.cell for p in ps)
    frontiers = [model.frontier(p, p.depth) for p in ps]

    out = []
    w = out.append
    w('-- This file is generated by tools/gen_puzzle_pkg.py from the puzzles in')
    w('-- puzzles/*.txt and the list in tools/puzzles.py ("make puzzles"). Do not edit.')
    w('--')
    w('-- The puzzles of the design, in the order of the keys 1 to 9. Each puzzle')
    w('-- (C_PUZZLES) is the size of the board, the pieces, and the slots of the')
    w('-- pieces (C_SLOTS, the slots of puzzle p are the entries first_slot to')
    w('-- first_slot + slots - 1). A slot is one orientation of one piece, see')
    w('-- tools/puzzles.py: its squares are given as linear offsets (row * cols +')
    w('-- column) from the lowest square of the slot (the anchor), and its extent as')
    w('-- the rows below the anchor (down), and the columns to the left (left) and to')
    w('-- the right (right) of it. The width of a puzzle is the largest offset plus')
    w('-- one, i.e. the width of the window of the engine, see engine.vhd.')
    w('--')
    w('-- The search of a puzzle is split at the depth "depth" between the contexts of')
    w('-- its engines (C_STAGES contexts each), and "frontier" is the number of nodes')
    w('-- at that depth, used for the progress. The size of a square on the')
    w('-- screen (cell), and the top left corner of the board (x0, y0), are in pixels')
    w('-- of the 1280x1024 screen, see board.vhd.')
    w('--')
    w('-- The puzzles:')
    for p, fr in zip(ps, frontiers):
        w(f'--   {p.index + 1}: {p.name:6} {len(p.pieces):2} pieces, {len(p.slots):3} slots, '
          f'width {p.width:3}, split at depth {p.depth} ({fr:,} nodes)')
    w('')
    w('library ieee;')
    w('use ieee.std_logic_1164.all;')
    w('')
    w('use work.util_pkg.all;')
    w('')
    w('package puzzle_pkg is')
    w('')
    w('   -- The number of pipeline stages of an engine, i.e. its number of contexts.')
    w('   -- Must match STAGES in tools/puzzles.py.')
    w(f'   constant C_STAGES      : positive := {puzzles.STAGES};')
    w('')
    w(f'   constant C_NUM_PUZZLES : positive := {len(ps)};')
    w(f'   constant C_MAX_SIZE    : positive := {max_size};   -- Squares of a piece')
    w(f'   constant C_MAX_PIECES  : positive := {max_pieces};')
    w(f'   constant C_MAX_SLOTS   : positive := {max_slots};')
    w(f'   constant C_MAX_WIDTH   : positive := {max_width};')
    w(f'   constant C_MAX_SQUARES : positive := {max_squares};')
    w(f'   constant C_MAX_ROWS    : positive := {max_rows};')
    w(f'   constant C_MAX_COLS    : positive := {max_cols};')
    w(f'   constant C_MAX_ENGINES : positive := {max_engines};')
    w(f'   constant C_MAX_CELL    : positive := {max_cell};   -- Pixels')
    w('')
    w('   type offsets_t is array (0 to C_MAX_SIZE-1) of natural range 0 to C_MAX_WIDTH-1;')
    w('')
    w('   type slot_t is record')
    w('      piece   : natural range 0 to C_MAX_PIECES-1;')
    w('      size    : natural range 1 to C_MAX_SIZE;')
    w('      down    : natural range 0 to C_MAX_ROWS-1;')
    w('      left    : natural range 0 to C_MAX_COLS-1;')
    w('      right   : natural range 0 to C_MAX_COLS-1;')
    w('      offsets : offsets_t;                     -- The first size entries')
    w('   end record slot_t;')
    w('')
    w('   type slot_vector is array (natural range <>) of slot_t;')
    w('')
    w('   type puzzle_t is record')
    w('      rows       : positive;')
    w('      cols       : positive;')
    w('      squares    : positive;')
    w('      pieces     : positive;')
    w('      slots      : positive;')
    w('      first_slot : natural;')
    w('      width      : positive;')
    w('      depth      : positive;')
    w('      frontier   : positive;')
    w('      cell       : positive;')
    w('      x0         : natural;')
    w('      y0         : natural;')
    w('      name       : string(1 to 5);')
    w('      title      : string(1 to 30);')
    w('   end record puzzle_t;')
    w('')
    w('   type puzzle_vector is array (natural range <>) of puzzle_t;')
    w('')
    w('   constant C_PUZZLES : puzzle_vector(0 to C_NUM_PUZZLES-1) := (')
    first = 0
    for n, (p, fr) in enumerate(zip(ps, frontiers)):
        end = ',' if n < len(ps) - 1 else ');'
        w(f'      (rows => {p.rows:2}, cols => {p.cols:2}, squares => {p.squares:3}, '
          f'pieces => {len(p.pieces):2}, slots => {len(p.slots):3}, first_slot => {first:3},')
        w(f'       width => {p.width:3}, depth => {p.depth}, frontier => {fr:7}, '
          f'cell => {p.cell:2}, x0 => {p.x0:3}, y0 => {p.y0:3},')
        w(f'       name => {vhdl_string(p.name, 5)}, title => {vhdl_string(p.title, 30)}){end}')
        first += len(p.slots)
    w('')
    w('   -- The number of engines of each puzzle on the MEGA65 and on the Nexys 4 DDR,')
    w('   -- see solver.vhd, mega65.vhd, and nexys4ddr.vhd')
    w(f"   constant C_ENGINES_MEGA65 : natural_vector(0 to C_NUM_PUZZLES-1) := ({', '.join(str(p.engines) for p in ps)});")
    w(f"   constant C_ENGINES_NEXYS  : natural_vector(0 to C_NUM_PUZZLES-1) := ({', '.join(str(p.nexys) for p in ps)});")
    w('')
    w('   -- The slots of all the puzzles')
    w(f'   constant C_SLOTS : slot_vector(0 to {first - 1}) := (')
    k = 0
    for p in ps:
        w(f'      -- {p.index + 1}: {p.name}')
        for s in p.slots:
            k += 1
            end = ',' if k < first else ');'
            offs = ', '.join(f'{o:3}' for o in s['offsets'])
            if len(s['offsets']) < max_size:
                offs += ', others => 0'
            w(f"      (piece => {s['piece']:2}, size => {len(s['offsets']):2}, "
              f"down => {s['down']}, left => {s['left']}, right => {s['right']},")
            w(f'       offsets => ({offs})){end}')
    w('')
    w('end package puzzle_pkg;')
    print('\n'.join(out))


if __name__ == '__main__':
    main()
